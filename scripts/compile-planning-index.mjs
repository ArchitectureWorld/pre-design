/** Reproduce the checked-in routing/identity projection from the approved, complete v1.2 JSON.
 * The source path is explicit. Never fetch or execute content from the specification. */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const SOURCE_SHA = '1ad0d7b0a2b52a84515cd97ab313c5596c0da02bea6175eaf4390d39d99d2a08'
const args = process.argv.slice(2), check = args.includes('--check'), paths = args.filter(a => a !== '--check')
if (paths.length !== 1) throw new Error('Usage: node scripts/compile-planning-index.mjs <approved-unified-data.json> [--check]')
const bytes = readFileSync(resolve(paths[0]))
if (createHash('sha256').update(bytes).digest('hex') !== SOURCE_SHA) throw new Error('SPEC_SOURCE_HASH_MISMATCH')
const data = JSON.parse(bytes.toString('utf8'))
const primary = data.dependencyEdges.filter(e => e.alternativeOf === null)
const alternatives = primary.filter(e => e.requiredWhen.op !== 'always').map(e => {
  const other = data.dependencyEdges.find(row => row.alternativeOf === e.edgeId)
  if (!other || e.requiredWhen.value !== true || other.requiredWhen.value !== false || other.groupId !== e.groupId) throw new Error('SPEC_ALTERNATIVE_INVALID')
  return [e.target, e.groupId.slice(`REQ-${e.target}-`.length), e.requiredWhen.field, e.source, e.selector.split('/').at(-1), other.source, other.selector.split('/').at(-1)]
})
const types = {}, extraPorts = {}, edgePorts = {}
for (const item of data.items) {
  for (const port of item.outputPorts) types[port.name] = port.type
  const extra = item.outputPorts.filter(p => p.name !== item.outputPort)
  if (extra.length) extraPorts[item.id] = extra.map(p => p.name)
}
for (const e of primary.filter(e => e.requiredWhen.op === 'always')) {
  const item = data.items.find(i => i.id === e.source)
  if (e.selector !== `/outputs/${item.outputPort}`) edgePorts[`${e.target}:${e.source}`] = e.selector.split('/').at(-1)
}
const seed = {
  schemaVersion: 'planning-index.v1', specVersion: 'planning-research.v1.2', sourceSha256: SOURCE_SHA,
  scope: 'identity-routing-artifact-candidates; not full professional execution schemas',
  chapters: data.chapters.map(c => [c.id,c.title]),
  modules: data.items.map(i => [i.id,i.title,i.outputPort,i.when.field ?? null,
    primary.filter(e => e.target === i.id).map(e => e.groupId.slice(`REQ-${i.id}-`.length)).join(' '),
    i.dataset,i.table.name,i.table.columns,i.figures.map(f => [f.name,f.type,f.template,f.sizePreset])]),
  portTypes: types, extraPorts, edgePorts, alternatives,
  legacy: data.legacyMap.map(r => [r.id,r.sourceObjectId,r.targets.join(' '),r.internalTargets.join(' ')]),
}
const target = resolve(import.meta.dirname, '../src/research-v2/catalog-data.ts')
const lines = Object.entries(seed).map(([key,value]) => {
  if (Array.isArray(value)) return `  ${JSON.stringify(key)}: [\n${value.map(row => '    '+JSON.stringify(row)).join(',\n')}\n  ]`
  return `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`
})
const output = '// Generated by scripts/compile-planning-index.mjs; see research/planning-v1.2/README.md.\nexport const PLANNING_INDEX_SEED = {\n'+lines.join(',\n')+'\n}\n'
if (check) {
  if (readFileSync(target,'utf8') !== output) throw new Error('SPEC_PROJECTION_DRIFT')
  console.log('PLANNING_V12_SOURCE_PROJECTION_PASS')
} else {
  writeFileSync(target, output, 'utf8')
  console.log('PLANNING_V12_INDEX_COMPILED')
}
